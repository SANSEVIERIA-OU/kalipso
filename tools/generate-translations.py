"""Build Qt/gettext catalogs, static website pages and package labels, offline.

Edit translations/catalogs/<language>.json, then run this script. --check checks
that every generated file matches its catalog. No translation service is used.
"""
import argparse
from collections import Counter
import html
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
I18N = ROOT / 'translations'
LOCALES = json.loads((I18N / 'locales.json').read_text(encoding='utf-8'))
SOURCE = json.loads((I18N / 'source.json').read_text(encoding='utf-8'))
STRUCTURE = json.loads((I18N / 'structure.json').read_text(encoding='utf-8'))
PLACEHOLDERS = re.compile(r'%(?:[1-9]\d*|[nsd])|\{(?:seconds|version)\}')
BASE = 'https://sansevieria-ou.github.io/kalipso/'


def encoded(value):
    return json.dumps(value, ensure_ascii=False)


def json_text(value):
    return json.dumps(value, ensure_ascii=False, indent=2) + '\n'


def validate(code, catalog):
    locale = next(x for x in LOCALES if x['code'] == code)
    if set(catalog) != set(SOURCE):
        raise ValueError(f'{code}: missing {set(SOURCE)-set(catalog)}, unknown {set(catalog)-set(SOURCE)}')
    for key, unit in SOURCE.items():
        value = catalog[key]
        if 'plural' in unit:
            if not isinstance(value, dict) or set(value) != set(locale['pluralCategories']):
                raise ValueError(f'{code}/{key}: expected plural categories {locale["pluralCategories"]}')
            values = value.values()
        else:
            values = [value]
        for translated in values:
            if not isinstance(translated, str) or not translated.strip():
                raise ValueError(f'{code}/{key}: empty translation')
            if Counter(PLACEHOLDERS.findall(translated)) != Counter(PLACEHOLDERS.findall(unit['source'])):
                raise ValueError(f'{code}/{key}: placeholders differ: {translated!r}')
            if re.findall(r'%[sd]', translated) != re.findall(r'%[sd]', unit['source']):
                raise ValueError(f'{code}/{key}: printf placeholder order differs')
            if translated.count('\n') != unit['source'].count('\n'):
                raise ValueError(f'{code}/{key}: line breaks differ')


def ts_catalog(locale, catalog, surface):
    root = ET.Element('TS', version='2.1', language=locale['qt'], sourcelanguage='en')
    contexts = {}
    for unit in STRUCTURE[surface]:
        name = unit['context']
        if name not in contexts:
            contexts[name] = ET.SubElement(root, 'context')
            ET.SubElement(contexts[name], 'name').text = name
        message = ET.SubElement(contexts[name], 'message', **({'numerus': 'yes'} if unit.get('numerus') else {}))
        ET.SubElement(message, 'source').text = unit['source']
        translated = catalog[unit['key']]
        tr = ET.SubElement(message, 'translation')
        if isinstance(translated, dict):
            for category in locale['qtPluralCategories']:
                ET.SubElement(tr, 'numerusform').text = translated[category]
        else:
            tr.text = translated
    ET.indent(root, space='    ')
    return '<?xml version="1.0" encoding="utf-8"?>\n<!DOCTYPE TS>\n' + ET.tostring(root, encoding='unicode') + '\n'


def po_catalog(locale, catalog):
    header = ('Project-Id-Version: kalipso-desktop\n'
              f'Language: {locale["gettext"]}\nMIME-Version: 1.0\n'
              'Content-Type: text/plain; charset=UTF-8\nContent-Transfer-Encoding: 8bit\n'
              f'Plural-Forms: {locale["gettextPlural"]}\n')
    lines = ['# SPDX-License-Identifier: AGPL-3.0-or-later',
             '# Generated from translations/catalogs; native-speaker review status: translations/locales.json.',
             'msgid ""', 'msgstr ' + encoded(header), '']
    for unit in STRUCTURE['desktop']:
        lines.append('msgid ' + encoded(unit['source']))
        translated = catalog[unit['key']]
        if unit.get('plural'):
            lines.append('msgid_plural ' + encoded(unit['plural']))
            for i, category in enumerate(locale['pluralCategories']):
                lines.append(f'msgstr[{i}] ' + encoded(translated[category]))
        else:
            lines.append('msgstr ' + encoded(translated))
        lines.append('')
    return '\n'.join(lines)


def native_registry():
    rows = ['// Generated by tools/generate-translations.py. SPDX-License-Identifier: LicenseRef-SANSEVIERIA-1.0',
            '#pragma once', '#include <QStringView>', 'namespace InterfaceLanguages {',
            'struct Language { const char *code; const char *name; const char *locale; bool rtl; bool reviewed; };',
            'inline constexpr Language all[] = {']
    for l in LOCALES:
        rows.append('    {' + ', '.join([encoded(l['code']), encoded(l['name']), encoded(l['qt']),
                                        'true' if l['direction'] == 'rtl' else 'false',
                                        'true' if l['review']['status'] in ('source', 'native-reviewed') else 'false']) + '},')
    rows += ['};', '// Integer CLDR plural rules. Compact-number exponents are zero for UI counts.',
             'inline int pluralIndex(QStringView code, int n) {']
    for l in LOCALES:
        expression = re.search(r'plural=(.*);$', l['gettextPlural']).group(1)
        rows.append(f'    if (code == u"{l["code"]}") return {expression};')
    rows += ['    return n == 1 ? 0 : 1;', '}', '} // namespace InterfaceLanguages', '']
    return '\n'.join(rows)


def website(locale, catalog, version):
    code = locale['code']
    prefix = '' if code == 'en' else '../'
    template = (I18N / 'site.html').read_text(encoding='utf-8')
    text = re.sub(r'\{\{(s[0-9a-f]+)\}\}',
                  lambda m: html.escape(catalog[m[1]].replace('{version}', version), quote=True), template)
    # Short hyphenated compounds stay together; translated phrases may wrap.
    text = re.sub(r'<span class="keep">([^<]+)</span>',
                  lambda m: m[0] if '-' in html.unescape(m[1]) and not re.search(r'\s', html.unescape(m[1])) and len(html.unescape(m[1])) < 25 else m[1], text)
    number_locale = locale['qt'].replace('_', '-')
    text = text.replace('<html lang="en">', f'<html lang="{code}" dir="{locale["direction"]}" data-number-locale="{number_locale}">')
    text = text.replace('="assets/', f'="{prefix}assets/')
    text = re.sub(r'<link rel="alternate"[^>]+>\n', '', text)
    url = BASE + ('' if code == 'en' else code + '/')
    links = f'<link rel="canonical" href="{url}">\n'
    links += '<link rel="alternate" hreflang="x-default" href="' + BASE + '">\n'
    for other in LOCALES:
        if not other['web']['hreflang']:
            continue
        links += f'<link rel="alternate" hreflang="{other["code"]}" href="{BASE}{"" if other["code"]=="en" else other["code"]+"/"}">\n'
    title = catalog['s79b9b113ba17']
    description = catalog['s8a3f34f21be6']
    image_url = BASE + f'assets/media/social-{code}.png'
    social = {
        'og:type': 'website', 'og:site_name': 'Kalipso', 'og:url': url,
        'og:title': title, 'og:description': description,
        'og:locale': locale['web']['openGraphLocale'],
        'og:image': image_url, 'og:image:secure_url': image_url,
        'og:image:type': 'image/png', 'og:image:width': '1200', 'og:image:height': '630',
        'og:image:alt': title,
    }
    for name, value in social.items():
        links += f'<meta property="{name}" content="{html.escape(value, quote=True)}">\n'
    for other in LOCALES:
        if other['code'] != code:
            links += f'<meta property="og:locale:alternate" content="{other["web"]["openGraphLocale"]}">\n'
    for name, value in {'card': 'summary_large_image', 'title': title, 'description': description,
                        'image': image_url, 'image:alt': title}.items():
        links += f'<meta name="twitter:{name}" content="{html.escape(value, quote=True)}">\n'
    # Factual software metadata, without invented reviews or ratings. This alone does not qualify
    # the page for Google's software-app review rich result.
    application = {
        '@context': 'https://schema.org', '@type': 'SoftwareApplication',
        '@id': BASE + '#software', 'name': 'Kalipso', 'url': url, 'description': description,
        'applicationCategory': 'MultimediaApplication',
        'operatingSystem': ['Linux', 'Windows 10 or later (x64)', 'macOS 14.4 or later (Apple Silicon)'],
        'softwareVersion': version, 'inLanguage': code, 'image': image_url,
        'downloadUrl': 'https://github.com/SANSEVIERIA-OU/kalipso/releases/latest',
        'sameAs': 'https://github.com/SANSEVIERIA-OU/kalipso',
        # The download/version record describes the published release, not the development tree.
        'license': 'https://github.com/SANSEVIERIA-OU/kalipso/blob/v' + version + '/LICENSE',
        'offers': {'@type': 'Offer', 'price': '0', 'priceCurrency': 'USD'},
    }
    data = encoded(application).replace('<', '\\u003c')
    links += '<script type="application/ld+json">' + data + '</script>\n'
    text = text.replace('<meta name="color-scheme"', links + '<meta name="color-scheme"')
    label = catalog[next(k for k, v in SOURCE.items() if v['source'] == 'Language')]
    options = []
    language_links = []
    for other in LOCALES:
        path = prefix + ('' if other['code'] == 'en' else other['code'] + '/')
        path = path or './'
        current = other['code'] == code
        current_attribute = ' aria-current="page"' if current else ''
        options.append(f'<option value="{path}" lang="{other["code"]}" dir="{other["direction"]}"'
                       f'{" selected" if current else ""}>{html.escape(other["name"])}</option>')
        language_links.append(f'<a href="{path}" hreflang="{other["code"]}" lang="{other["code"]}" '
                              f'dir="{other["direction"]}"{current_attribute} data-language>{html.escape(other["name"])}</a>')
    picker = f'<select id="site-language" hidden aria-label="{html.escape(label, quote=True)}">' + ''.join(options) + '</select>'
    picker += f'<a id="language-link" href="#languages">{html.escape(label)}</a>'
    text = re.sub(r'<a href="it/"[^>]*data-language>.*?</a>', picker, text, count=1)
    text = re.sub(r'<nav aria-label="[^"]*" class="languages">.*?</nav>',
                  f'<nav id="languages" aria-label="{html.escape(label, quote=True)}" class="languages">' + ''.join(language_links) + '</nav>', text)
    if locale['review']['status'] == 'pending-native-review':
        review = html.escape(catalog['sf473757c73ad'])
        text = text.replace('<nav id="languages"', f'<p class="translation-status">{review}</p><nav id="languages"')
    # Keep the released download's licence distinct from the current source revision.
    current = ('Sorgente attuale dell’app: ' if code == 'it' else 'Current app source: ')
    detail = ('Le versioni pubblicate fino alla 2.9 mantengono AGPL. Le integrazioni desktop hanno termini separati.'
              if code == 'it' else
              'Published versions through 2.9 retain AGPL. Desktop integrations have separate terms.')
    note = ('<p class="translation-status" lang="' + ('it' if code == 'it' else 'en') + '">'
            + current + '<a href="https://github.com/SANSEVIERIA-OU/kalipso/blob/main/LICENSE">SANSEVIERIA <span class="keep">License 1.0</span></a>. '
            + detail + ' <a href="https://github.com/SANSEVIERIA-OU/kalipso/blob/main/NOTICE">NOTICE</a>.</p>')
    text = text.replace(' </div>\n</footer>', '  ' + note + '\n </div>\n</footer>')
    return '<!-- Generated from translations/site.html and translations/catalogs. -->\n' + text


def sitemap():
    # No fabricated lastmod dates: omit them until content-change dates are maintained explicitly.
    namespace = 'http://www.sitemaps.org/schemas/sitemap/0.9'
    xhtml = 'http://www.w3.org/1999/xhtml'
    ET.register_namespace('', namespace)
    ET.register_namespace('xhtml', xhtml)
    root = ET.Element(f'{{{namespace}}}urlset')
    for locale in LOCALES:
        entry = ET.SubElement(root, f'{{{namespace}}}url')
        ET.SubElement(entry, f'{{{namespace}}}loc').text = BASE + ('' if locale['code'] == 'en' else locale['code'] + '/')
        for other in LOCALES:
            if other['web']['hreflang']:
                ET.SubElement(entry, f'{{{xhtml}}}link', rel='alternate', hreflang=other['web']['hreflang'],
                              href=BASE + ('' if other['code'] == 'en' else other['code'] + '/'))
        ET.SubElement(entry, f'{{{xhtml}}}link', rel='alternate', hreflang='x-default', href=BASE)
    ET.indent(root, space='  ')
    return '<?xml version="1.0" encoding="UTF-8"?>\n' + ET.tostring(root, encoding='unicode') + '\n'


def web_strings(catalog):
    flat = {name: catalog[key] for name, key in STRUCTURE['web'].items()}
    nested = {}
    for name, value in flat.items():
        if '.' in name:
            parent, child = name.split('.', 1)
            nested.setdefault(parent, {})[child] = value
        else:
            nested[name] = value
    seconds = nested.pop('secondsLeft')
    return ('// Generated by tools/generate-translations.py. SPDX-License-Identifier: AGPL-3.0-or-later\n'
            'export default {...' + encoded(nested) + ', secondsLeft: s => ' + encoded(seconds)
            + '.replace("{seconds}", new Intl.NumberFormat(document.documentElement.dataset.numberLocale || document.documentElement.lang).format(s))};\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--available', action='store_true', help=argparse.SUPPRESS)
    args = parser.parse_args()
    version = re.search(r'project\(Kalipso VERSION ([0-9.]+)', (ROOT / 'CMakeLists.txt').read_text(encoding='utf-8'))[1]
    outputs = {ROOT / 'src/interface_languages.h': native_registry(), ROOT / 'site/sitemap.xml': sitemap()}
    catalogs = {}
    for locale in LOCALES:
        code = locale['code']; path = I18N / 'catalogs' / (code + '.json')
        if args.available and not path.exists():
            continue
        catalog = json.loads(path.read_text(encoding='utf-8')); validate(code, catalog); catalogs[code] = catalog
        file_code = code.replace('-', '_')
        for surface, prefix in [('app', 'kalipso'), ('engine', 'kalipso-engine')]:
            outputs[I18N / f'{prefix}_{file_code}.ts'] = ts_catalog(locale, catalog, surface)
        outputs[ROOT / 'desktop/po' / f'{locale["gettext"]}.po'] = po_catalog(locale, catalog)
        outputs[ROOT / 'site' / ('' if code == 'en' else code) / 'index.html'] = website(locale, catalog, version)
        outputs[ROOT / 'site/assets/strings' / (code + '.mjs')] = web_strings(catalog)
        # CLDR has more integer forms than some Qt versions (e.g. Irish, Maltese).
        # The application translator uses these exact forms before falling back to the .qm.
        plurals = {u['context'] + '\x04' + u['source']: [catalog[u['key']][category] for category in locale['pluralCategories']]
                   for u in STRUCTURE['app'] + STRUCTURE['engine'] if u.get('numerus')}
        outputs[I18N / 'plurals' / (code + '.json')] = json_text(plurals)

    # AppStream preserves historical release notes and other independently maintained metadata.
    meta_path = ROOT / 'packaging/io.github.sansevieria_ou.kalipso.metainfo.xml'
    meta = ET.fromstring(meta_path.read_text(encoding='utf-8')); lang = '{http://www.w3.org/XML/1998/namespace}lang'
    for child in list(meta):
        if child.tag in ['summary', 'description'] and lang in child.attrib: meta.remove(child)
    base_description = meta.find('description')
    for parent in base_description.iter():
        for child in list(parent):
            if lang in child.attrib: parent.remove(child)
    for code, catalog in catalogs.items():
        if code == 'en': continue
        summary = ET.Element('summary', {lang: code})
        summary.text = catalog[STRUCTURE['metadata'][meta.findtext('summary')]]
        meta.insert(list(meta).index(base_description), summary)
        for node in list(base_description):
            if lang in node.attrib: continue
            if node.tag in ('ul', 'ol'):
                for item in list(node):
                    if lang in item.attrib: continue
                    copy = ET.fromstring(ET.tostring(item)); copy.set(lang, code)
                    copy.text = catalog[STRUCTURE['metadata'][item.text.strip()]]
                    node.append(copy)
            else:
                copy = ET.fromstring(ET.tostring(node)); copy.set(lang, code)
                copy.text = catalog[STRUCTURE['metadata'][node.text.strip()]]
                base_description.append(copy)
    ET.indent(meta, space='  ')
    outputs[meta_path] = '<?xml version="1.0" encoding="UTF-8"?>\n' + ET.tostring(meta, encoding='unicode') + '\n'
    desktop_path = ROOT / 'packaging/io.github.sansevieria_ou.kalipso.desktop'
    lines = [x for x in desktop_path.read_text(encoding='utf-8').splitlines() if not re.match(r'(Comment|GenericName|Keywords)\[', x)]
    for code, catalog in catalogs.items():
        if code == 'en': continue
        for name in ['GenericName', 'Comment', 'Keywords']:
            source = next(line.split('=', 1)[1] for line in lines if line.startswith(name + '='))
            lines.append(f'{name}[{next(l["gettext"] for l in LOCALES if l["code"] == code)}]={catalog[STRUCTURE["metadata"][source]]}')
    outputs[desktop_path] = '\n'.join(lines) + '\n'
    plasma_path = ROOT / 'desktop/plasma/metadata.json'
    plasma = json.loads(plasma_path.read_text(encoding='utf-8')); plugin = plasma['KPlugin']
    for key in list(plugin):
        if key.startswith(('Name[', 'Description[')): del plugin[key]
    for code, catalog in catalogs.items():
        if code != 'en':
            plugin[f'Name[{next(l["gettext"] for l in LOCALES if l["code"] == code)}]'] = 'Kalipso'
            plugin[f'Description[{next(l["gettext"] for l in LOCALES if l["code"] == code)}]'] = catalog[STRUCTURE['metadata'][plugin['Description']]]
    outputs[plasma_path] = json_text(plasma)
    stale = []
    for path, text in outputs.items():
        if not path.exists() or path.read_text(encoding='utf-8') != text:
            stale.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True); path.write_text(text, encoding='utf-8', newline='\n')
    if args.check and stale:
        raise SystemExit('Generated translations differ: ' + ', '.join(stale))
    print(f'{len(catalogs)} languages, {len(SOURCE)} units each; {len(outputs)} generated files; {len(stale)} changed.')


if __name__ == '__main__':
    main()
