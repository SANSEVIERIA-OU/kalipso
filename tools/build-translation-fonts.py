"""Rebuild bundled OFL fallbacks using Debian fonts-noto-core/fonts-noto-cjk and fonttools.
Full alphabet fonts support user scripts; CJK subsets cover the interface and autonyms.
"""
from pathlib import Path
import json
import shutil
from fontTools.ttLib import TTFont
from fontTools import subset
ROOT = Path(__file__).resolve().parent.parent
out = ROOT/'src/fonts'; web = ROOT/'site/assets/fonts'
characters = ''.join(p.read_text(encoding='utf-8') for p in (ROOT/'translations/catalogs').glob('*.json'))
characters += (ROOT/'translations/locales.json').read_text(encoding='utf-8')
css = ['/* Generated by tools/build-translation-fonts.py; bundled Noto fonts, SIL OFL 1.1. */']
fonts = [('NotoSans',None), ('NotoSansArabic',None), ('NotoSansDevanagari',None),
         ('NotoSansBengali',None), ('NotoSansTelugu',None), ('NotoSansCJKjp',0), ('NotoSansCJKsc',2)]
for name,index in fonts:
    for weight in ['Regular','Bold']:
        if index is None:
            src=Path('/usr/share/fonts/truetype/noto')/f'{name}-{weight}.ttf'
            font=TTFont(src, recalcTimestamp=False); dest=out/src.name
            shutil.copyfile(src,dest)
        else:
            src=Path('/usr/share/fonts/opentype/noto')/f'NotoSansCJK-{weight}.ttc'
            font=TTFont(src,fontNumber=index,recalcTimestamp=False)
            options=subset.Options(); options.layout_features=['*']; options.name_IDs=['*']
            sub=subset.Subsetter(options=options); sub.populate(text=characters); sub.subset(font)
            dest=out/f'{name}-{weight}.otf'; font.save(dest)
        # Separate CSS ranges keep unrelated scripts from downloading these fonts.
        cmap=font.getBestCmap(); points=sorted(cmap)
        family='Noto CJK JP' if index==0 else 'Noto CJK SC' if index==2 else 'Noto Interface'
        ranges=[]; start=end=points[0]
        for point in points[1:]+[0x110000]:
            if point==end+1: end=point; continue
            ranges.append(f'U+{start:X}'+(f'-{end:X}' if end!=start else ''))
            start=end=point
        font.flavor='woff2'; filename=dest.stem+'.woff2'; font.save(web/filename)
        css.append(f"@font-face{{font-family:'{family}';font-style:normal;font-weight:{400 if weight=='Regular' else 700};font-display:swap;src:url(fonts/{filename}) format('woff2');unicode-range:{','.join(ranges)}}}")
for package in ['fonts-noto-core','fonts-noto-cjk']:
    for folder in [out,web]:
        shutil.copyfile(f'/usr/share/doc/{package}/copyright',folder/f'{package}-LICENSE.txt')
(ROOT/'site/assets/noto-fonts.css').write_text('\n'.join(css)+'\n', encoding='utf-8', newline='\n')
print('Bundled Noto fallback fonts rebuilt.')
